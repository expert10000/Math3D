import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { closeSurfaceApp, launchSurfaceApp, resetSurfaceAppState, type LaunchedSurfaceApp } from "./helpers/surfaceAppHarness";
import { freezeControls } from "./helpers/projectFreeze";

test("PC19 presents an exact saved Mesh pair in a durable Workbook", async () => {
  test.setTimeout(180_000);
  let ctx: LaunchedSurfaceApp | null = null;
  try {
    ctx = await launchSurfaceApp(); await resetSurfaceAppState(ctx.page);
    const page = ctx.page, controls = freezeControls(page), panel = controls.panel;
    await controls.show();
    await panel.getByRole("button", { name: "Starter projects", exact: true }).click();
    await panel.getByTestId("project-library-search").fill("Saved Mesh Comparison Study");
    await panel.getByTestId("project-template-open-mesh-comparison-study").click();
    await panel.getByTestId("project-open-mesh-result-trend").click();
    const trend = page.getByTestId("project-mesh-result-trend");
    await trend.getByTestId("project-mesh-trend-metric").selectOption("metrics.triangleArea.avg");
    const points = trend.getByTestId("project-mesh-trend-plot").locator("g[role=button]");
    await expect(points).toHaveCount(3);
    await points.nth(0).locator("circle").click();
    await trend.getByTestId("project-mesh-trend-pin-a").click();
    await points.nth(2).locator("circle").click();
    await trend.getByTestId("project-mesh-trend-pin-b").click();
    await trend.getByTestId("project-mesh-trend-compare").click();
    const comparison = page.getByTestId("project-mesh-result-comparison");
    await comparison.getByTestId("project-mesh-pinned-title").fill("Starter generations A/B");
    await comparison.getByTestId("project-mesh-pinned-save").click();
    await expect(comparison.getByRole("status")).toContainText("saved to this Project");
    await comparison.getByTestId("project-mesh-result-return").click();
    await trend.getByRole("button", { name: "Close" }).click();
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("math3d.project.v1")!));
    const pair = saved.savedMeshComparisons?.find((item: { title: string }) => item.title === "Starter generations A/B");
    expect(pair).toBeTruthy();
    await controls.hide();
    await page.getByRole("button", { name: "Surfaces", exact: true }).first().click();
    await page.getByRole("button", { name: "Workbook", exact: true }).first().click();
    await page.getByRole("button", { name: /^3 Visualize$/ }).click();
    await page.getByTestId("workbook-saved-mesh-comparison-select").first().selectOption(pair.id);
    const embedded = page.getByTestId("workbook-saved-mesh-comparison").first();
    await expect(embedded).toContainText("Exact saved pair linked");
    await embedded.getByText("Show embedded saved Mesh comparison").click();
    const evidence = embedded.getByTestId("workbook-saved-mesh-comparison-evidence");
    await expect(evidence).toContainText("2.03125");
    await expect(evidence).toContainText(pair.a.resultHash);
    const report = test.info().outputPath("pc19-workbook-saved-mesh-comparison.html");
    await ctx.app.evaluate(({ session }, path) => session.defaultSession.once("will-download", (_event, item) => item.setSavePath(path)), report);
    await embedded.getByTestId("workbook-saved-mesh-comparison-export").click();
    await expect.poll(() => { try { return readFileSync(report).length > 0; } catch { return false; } }, { timeout: 30_000 }).toBe(true);
    expect(readFileSync(report, "utf8")).toContain(pair.b.sourceHash);
    await embedded.getByText("Show embedded saved Mesh comparison").click();
    await expect(evidence).toHaveCount(0);
    await controls.show();
    await panel.getByTestId("project-save-active-workbook").click();
    await expect(panel.getByTestId("project-message")).toContainText("Added");
    const withBook = await page.evaluate(() => JSON.parse(localStorage.getItem("math3d.project.v1")!));
    const workbookId = withBook.workbooks?.find((item: { id: string }) =>
      !saved.workbooks?.some((prior: { id: string }) => prior.id === item.id))?.id;
    expect(workbookId).toBeTruthy();
    await page.reload();
    await controls.show();
    await panel.getByTestId(`project-preview-${withBook.identity.id}`).click();
    await panel.getByTestId("project-restore-saved").click();
    await panel.getByTestId("project-import-cancel").click();
    await panel.getByTestId(`project-open-workbook-${workbookId}`).click();
    await page.getByRole("button", { name: "Surfaces", exact: true }).first().click();
    await page.getByRole("button", { name: "Workbook", exact: true }).first().click();
    await page.getByRole("button", { name: /^3 Visualize$/ }).click();
    const reopened = page.getByTestId("workbook-saved-mesh-comparison").first();
    await expect(reopened).toContainText("Exact saved pair linked");
    await reopened.getByText("Show embedded saved Mesh comparison").click();
    await expect(reopened.getByTestId("workbook-saved-mesh-comparison-evidence")).toContainText(pair.b.resultId);
    const publication = page.getByTestId("workbook-publication").first();
    await publication.locator("summary").click();
    const reopenedReport = test.info().outputPath("pc19-reopened-workbook.html");
    await ctx.app.evaluate(({ session }, path) => session.defaultSession.once("will-download", (_event, item) => item.setSavePath(path)), reopenedReport);
    await publication.getByRole("button", { name: "Export selected HTML" }).click();
    await expect.poll(() => { try { return readFileSync(reopenedReport, "utf8").includes(pair.b.resultHash); } catch { return false; } }, { timeout: 30_000 }).toBe(true);
  } finally { await closeSurfaceApp(ctx); }
});
