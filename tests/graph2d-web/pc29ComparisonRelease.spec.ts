import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { pc29ComparisonProject } from "../e2e/helpers/pc29ComparisonFixture";

test("PC29 browser reopens one portable Project's Mesh trend, A/B pairs and coordinate review", async ({ page }) => {
  const fixture = pc29ComparisonProject();
  await page.goto("/");
  await page.evaluate(() => { localStorage.clear(); localStorage.setItem("math3d.computeEngines.firstLaunchSeen", "1"); });
  await page.reload();
  await page.getByTestId("projects-toggle").click();
  const panel = page.getByTestId("project-explorer-panel");
  await panel.getByTestId("project-import-file").setInputFiles({ name: "pc29.resources.json",
    mimeType: "application/json", buffer: Buffer.from(fixture.raw) });
  await panel.getByTestId("project-import-open").click();
  await panel.getByTestId("project-gallery-layout-toggle").click();
  await panel.getByTestId("project-save").click();
  await expect(panel.getByTestId("project-message")).toContainText("Saved");
  await page.reload();
  await page.getByTestId("projects-toggle").click();
  await panel.getByTestId(`project-preview-${fixture.projectId}`).click();
  await panel.getByTestId("project-restore-saved").click();
  await panel.getByTestId("project-import-open").click();
  const review = panel.getByTestId("project-saved-mesh-comparisons");
  await expect(review.locator("article")).toHaveCount(3);
  await panel.getByTestId("project-open-mesh-result-trend").click();
  const trend = page.getByTestId("project-mesh-result-trend");
  await trend.getByTestId("project-mesh-trend-anchor").selectOption(fixture.resultIds[0]!);
  await trend.getByTestId("project-mesh-trend-metric").selectOption("metrics.triangleArea.avg");
  await expect(trend.getByTestId("project-mesh-trend-status")).toContainText("3 verified recorded points");
  await trend.getByTestId(`project-mesh-trend-point-${fixture.resultIds[1]}`).locator("circle").click();
  await trend.getByTestId("project-mesh-trend-open-result").click();
  const result = panel.getByTestId("project-result-detail");
  await expect(result).toContainText(fixture.resultIds[1]!);
  await result.getByTestId("project-open-exact-mesh-generation").click();
  const generation = page.getByTestId("project-mesh-generation-preview");
  await expect.poll(() => generation.locator("canvas").count()).toBeGreaterThan(0);
  await generation.getByRole("button", { name: "Return to saved result" }).click();
  await expect(generation).toHaveCount(0);
  await review.getByTestId(`project-open-pinned-mesh-${fixture.pairIds[0]}`).click();
  const pair = page.getByTestId("project-mesh-result-comparison");
  await expect(pair.getByTestId("project-mesh-result-status")).toContainText("compatible");
  await pair.getByTestId("project-mesh-result-return").click();
  await panel.getByRole("button", { name: "Documents", exact: true }).click();
  await panel.getByTestId(`project-open-workbook-${fixture.workbookId}`).click();
  await page.getByRole("button", { name: "Surfaces", exact: true }).first().click();
  await page.getByRole("button", { name: "Workbook", exact: true }).first().click();
  await page.getByRole("button", { name: /^3 Visualize$/ }).click();
  const workbookReview = page.getByTestId("workbook-coordinate-review").first();
  await workbookReview.getByText("Show embedded coordinate review").click();
  await expect(workbookReview.getByTestId(`workbook-coordinate-review-row-${fixture.noteId}`)).toContainText("verified");
  const download = page.waitForEvent("download");
  await workbookReview.getByRole("button", { name: "Export coordinate review HTML" }).click();
  expect(readFileSync((await (await download).path())!, "utf8")).toContain("Authored PC29 coordinate observation.");
  await workbookReview.getByRole("button", { name: "Open saved marker" }).click();
  const comparison = page.getByTestId("project-composition-view");
  await expect(comparison.getByLabel("Saved composition")).toHaveValue(fixture.compositionId);
  await expect(comparison.getByTestId("project-composition-probe-status")).toContainText("Saved coordinate");
  const canvas = await comparison.locator("canvas").first().elementHandle();
  await comparison.getByRole("button", { name: "Close" }).click();
  await expect(comparison).toHaveCount(0);
  if (canvas) await expect.poll(() => canvas.evaluate(element => element.isConnected)).toBe(false);
});

test("PC29 browser refuses changed Note and Mesh bytes in the multi-feature portable Project", async ({ page }) => {
  const packaged = JSON.parse(pc29ComparisonProject().raw);
  await page.goto("/");
  await page.evaluate(() => { localStorage.clear(); localStorage.setItem("math3d.computeEngines.firstLaunchSeen", "1"); });
  await page.reload();
  await page.getByTestId("projects-toggle").click();
  const panel = page.getByTestId("project-explorer-panel");
  const changedNote = structuredClone(packaged);
  changedNote.project.notes.find((item: { title: string }) => item.title === "PC29 coordinate").body = "Forged";
  await panel.getByTestId("project-import-file").setInputFiles({ name: "pc29-note-changed.resources.json",
    mimeType: "application/json", buffer: Buffer.from(JSON.stringify(changedNote)) });
  await expect(panel.getByTestId("project-message")).toContainText("Project import rejected");
  await expect(panel.getByTestId("project-import-open")).toHaveCount(0);
  const changedMesh = structuredClone(packaged);
  const sidecar = changedMesh.resources.find((item: { kind: string }) => item.kind === "mesh-buffers");
  sidecar.data = (sidecar.data[0] === "A" ? "B" : "A") + sidecar.data.slice(1);
  await panel.getByTestId("project-import-file").setInputFiles({ name: "pc29-mesh-changed.resources.json",
    mimeType: "application/json", buffer: Buffer.from(JSON.stringify(changedMesh)) });
  await expect(panel.getByTestId("project-message")).toContainText("Project import rejected");
  await expect(panel.getByTestId("project-import-open")).toHaveCount(0);
});
